import type { Text } from '../i18n/locales'

/**
 * Wendy's photographs. Only her own work belongs here — no stock or AI images.
 *
 * To add a photo:
 *   1. Put the original in content/photography/ and run `npm run images`.
 *   2. Add an entry with `image: '<key>'` (file name in lowercase with dashes).
 *   3. Fill in only what is true; leave unknown fields out. A missing title shows as "Untitled".
 *
 * Entries with `placeholder` render as labelled empty frames until real photos arrive.
 */
export type PhotoCategory = 'travel' | 'landscape' | 'street' | 'everyday'

export const photoCategories: PhotoCategory[] = ['travel', 'landscape', 'street', 'everyday']

export interface Photo {
  id: string
  /** Asset key from src/data/image-manifest.json (generated by `npm run images`). */
  image?: string
  /** Optional different asset key for the grid thumbnail (e.g. a tighter crop). */
  thumbnail?: string
  title?: Text
  location?: Text
  year?: string
  category: PhotoCategory
  description?: Text
  /** Placeholder only: width / height of the empty frame. */
  placeholder?: { ratio: number }
}

